class TestOutput(TranscriptCase):

    def test_text_report_names_the_headline_numbers(self):
        self.write([rec_nudge(NUDGE_CREATE), rec_launch("41"),
                    rec_result(report_text("check_failure", "41"))])
        buf = io.StringIO()
        with redirect_stdout(buf):
            fr.print_text(self.report(), 15)
        out = buf.getvalue()
        self.assertIn("Nudges fired: 1", out)
        self.assertIn("Watchers launched: 1", out)
        self.assertIn("Follow-through: 100%", out)
        self.assertIn("check_failure", out)

    def test_empty_report_says_so(self):
        buf = io.StringIO()
        with redirect_stdout(buf):
            fr.print_text(fr.build_report(fr.collect([], None, "")), 15)
        self.assertIn("No pr-sentinel activity", buf.getvalue())

    def test_json_output_is_valid_and_complete(self):
        self.write([rec_nudge(NUDGE_CREATE), rec_launch("41"),
                    rec_result(report_text("ready", "41"))])
        proc = subprocess.run(
            [sys.executable, str(SCRIPT), "--transcripts", str(self.root),
             "--since", "all", "--json"],
            capture_output=True, text=True)
        self.assertEqual(0, proc.returncode, proc.stderr)
        data = json.loads(proc.stdout)
        self.assertEqual(1, data["nudges_total"])
        self.assertEqual(1, data["launches"])
        self.assertEqual({"ready": 1}, data["events"])
        self.assertEqual(100.0, data["follow_through"])

    def test_exits_nonzero_with_no_transcripts(self):
        empty = tempfile.mkdtemp()
        proc = subprocess.run(
            [sys.executable, str(SCRIPT), "--transcripts", empty],
            capture_output=True, text=True)
        self.assertNotEqual(0, proc.returncode)


class TestRobustness(TranscriptCase):

    def test_malformed_lines_are_skipped(self):
        path = self.write([rec_launch("41")])
