class TestLaunches(TranscriptCase):

    def test_counts_a_real_launch(self):
        self.write([rec_launch("41")])
        r = self.report()
        self.assertEqual(1, r["launches"])
        self.assertEqual(0, r["launches_foreground"])

    def test_flags_a_foreground_launch(self):
        self.write([rec_launch("41", background=False)])
        r = self.report()
        self.assertEqual(1, r["launches"])
        self.assertEqual(1, r["launches_foreground"])

    def test_mentioning_the_script_is_not_a_launch(self):
        """The defect that made the first draft report 2558 launches where 2372
        happened: every grep, cat, find and heredoc naming the script counted."""
        mentions = [
            'grep -n "WATCH_UNTIL" %s' % WATCHER_PATH,
            'git diff scripts/pr-sentinel-watch.sh',
            'find ~/.claude -name pr-sentinel-watch.sh',
            'cat > tests/test_watcher.py <<EOF\npr-sentinel-watch.sh\nEOF',
            'shellcheck scripts/pr-sentinel-watch.sh',
        ]
        self.write([rec_bash(c, tool_use_id="t%d" % i)
                    for i, c in enumerate(mentions)])
        self.assertEqual(0, self.report()["launches"])

    def test_launch_survives_a_cd_prefix_and_redirect(self):
        self.write([rec_launch(
            "41", command='cd /synthetic/repo && bash "%s" 41 > /dev/null 2>&1'
                          % WATCHER_PATH)])
        self.assertEqual(1, self.report()["launches"])

    def test_launch_command_from_the_nudge_is_recognised(self):
        """The nudge prints the exact command to run; whatever it prints must
        parse as a launch, or follow-through reads as zero."""
        m = re.search(r'^\s*(bash "[^"]+" \S+)\s*$', NUDGE_CREATE, re.M)
        self.assertIsNotNone(m, "the nudge no longer prints a bash command")
        self.write([rec_launch("41", command=m.group(1))])
        self.assertEqual(1, self.report()["launches"])


