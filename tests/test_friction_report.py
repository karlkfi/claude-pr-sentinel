class TestEventContract(unittest.TestCase):

    def test_event_kinds_cover_every_watcher_event(self):
        """A new watcher event must be classified here, or the report buckets
        it as 'unknown' and the ranking quietly loses meaning."""
        emitted = watcher_event_names()
        self.assertTrue(emitted, "no report_header call sites found — the "
                                 "signature regex has drifted from the watcher")
        missing = emitted - set(fr.EVENT_KIND)
        self.assertEqual(set(), missing,
                         "the watcher emits these and EVENT_KIND does not "
                         "classify them: %s" % sorted(missing))

    def test_event_kinds_names_no_event_the_watcher_dropped(self):
        stale = set(fr.EVENT_KIND) - watcher_event_names()
        self.assertEqual(set(), stale,
                         "EVENT_KIND classifies events the watcher no longer "
                         "emits: %s" % sorted(stale))

    def test_every_kind_has_a_hint(self):
        self.assertEqual(set(fr.EVENT_KIND.values()), set(fr.KIND_HINT))

    def test_contract_test_can_fail(self):
        """The coverage test is only worth having if a dropped classification
        actually fails it."""
        emitted = watcher_event_names()
        self.assertIn("ready", emitted)
        trimmed = dict(fr.EVENT_KIND)
        trimmed.pop("ready")
        self.assertTrue(emitted - set(trimmed))


