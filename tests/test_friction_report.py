class TestEvents(TranscriptCase):

    def test_counts_a_plain_report(self):
        self.write([rec_result(report_text("check_failure", "41"))])
        r = self.report()
        self.assertEqual(1, r["events_total"])
        self.assertEqual(1, r["events"]["check_failure"])
        self.assertEqual(1, r["kinds"]["work"])

    def test_counts_a_line_numbered_report(self):
        """A backgrounded watcher's report reaches the session as a task-output
        file, and a Read of it arrives line-numbered. Missing this shape drops
        most real events."""
        self.write([rec_result(numbered(report_text("ready", "41")))])
        r = self.report()
        self.assertEqual(1, r["events_total"])
        self.assertEqual(1, r["events"]["ready"])

    def test_report_after_watcher_warnings_still_counts(self):
        text = ("pr-sentinel-watch: WARNING: gh query failed transiently\n"
                + report_text("conflict", "41"))
        self.write([rec_result(numbered(text))])
        self.assertEqual(1, self.report()["events"]["conflict"])

    def test_multiple_reports_in_one_output_file(self):
        """A non-exiting notice and the final event share an output file."""
        text = (report_text("ready_watching", "41") + "\n"
                + report_text("conflict", "41"))
        self.write([rec_result(text)])
        r = self.report()
        self.assertEqual(1, r["events"]["ready_watching"])
        self.assertEqual(1, r["events"]["conflict"])

    def test_header_without_a_pr_line_is_not_a_report(self):
        """The watcher's own source reads `report_header` / `$1`; requiring the
        PR line is what keeps a source read from counting as usage."""
        self.write([rec_result('echo "PR-SENTINEL EVENT: $1"\necho "PR: ${PR}"')])
        self.assertEqual(0, self.report()["events_total"])

    def test_marker_inside_a_test_file_is_not_a_report(self):
        """An assertion naming the marker has no `PR:` line under it."""
        source = ('import unittest\n'
                  '    self.assertIn("PR-SENTINEL EVENT: ready", out)\n'
                  '    self.assertIn("PR: 41", out)\n')
        self.write([rec_result(numbered(source))])
        self.assertEqual(0, self.report()["events_total"])

    def test_marker_not_at_line_start_is_not_a_report(self):
        """The case the start-anchor alone defends against: a fixture that
        assigns a whole report to a variable puts the header mid-line, with a
        clean `PR:` line directly under it. The PR-line requirement cannot
        reject this one, so a substring match would count it as usage."""
        source = ('out = """PR-SENTINEL EVENT: ready\n'
                  'PR: 41\n'
                  'State: OPEN"""\n')
        self.write([rec_result(numbered(source))])
        self.assertEqual(0, self.report()["events_total"])

    def test_reading_the_same_output_twice_counts_once(self):
        """352 of 2054 raw matches in the local corpus, 17%, are the same file
        read a second time."""
        text = report_text("ready", "41")
        self.write([rec_result(text, tool_use_id="a"),
                    rec_result(numbered(text), tool_use_id="b")])
        self.assertEqual(1, self.report()["events_total"])

    def test_two_distinct_runs_on_one_pr_both_count(self):
        """Dedup keys on the report body, so a genuinely different verdict for
        the same PR is not collapsed."""
        self.write([
            rec_result(report_text("check_failure", "41", "State: OPEN"),
                       tool_use_id="a"),
            rec_result(report_text("check_failure", "41", "State: REOPENED"),
                       tool_use_id="b")])
        self.assertEqual(2, self.report()["events_total"])

    def test_dedup_is_scoped_to_one_session(self):
        text = report_text("ready", "41")
        self.write([rec_result(text)])
        self.write([rec_result(text)])
        self.assertEqual(2, self.report()["events_total"])


