#!/usr/bin/env python3
"""Tests for scripts/friction-report.py.

Run with: python3 -m unittest discover tests

The friction report is a read-only analyzer over what Claude Code persists in
~/.claude/projects/**/*.jsonl. These tests build synthetic transcript files and
assert the report's detection, joins and rankings — never touching a real
transcript.

Signature fidelity: the nudge and Stop-block fixtures are generated by calling
the hooks' own message builders, and the event names come from the watcher's
own `report_header` call sites — not from hand-copied strings. A wording change
that broke a detector therefore fails these tests instead of silently reporting
real usage as zero.

Fixture rule (as elsewhere in this suite): synthetic PR numbers and paths only.
"""
import io
import json
import os
import re
import subprocess
import sys
import tempfile
import unittest
from contextlib import redirect_stdout
from importlib import util
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SCRIPT = REPO / "scripts" / "friction-report.py"
HOOK = REPO / "scripts" / "pr-sentinel-hook.py"
STOP_HOOK = REPO / "scripts" / "pr-sentinel-stop-hook.py"
GUARD = REPO / "scripts" / "pr-sentinel-guard.py"
WATCHER = REPO / "scripts" / "pr-sentinel-watch.sh"

# A synthetic plugin root, so the generated nudge names a watcher path with the
# same shape as a real install without pointing at one.
PLUGIN_ROOT = "/synthetic/plugins/pr-sentinel"


def _load(path, name):
    """Filenames have dashes, so import by path."""
    spec = util.spec_from_file_location(name, path)
    mod = util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


fr = _load(SCRIPT, "friction_report")
hook = _load(HOOK, "pr_sentinel_hook")
stop_hook = _load(STOP_HOOK, "pr_sentinel_stop_hook")
guard = _load(GUARD, "pr_sentinel_guard")
overlap = _load(REPO / "scripts" / "pr_sentinel_overlap.py", "pr_sentinel_overlap")

# Every reason the guard hands to `permissionDecisionReason`, and the real text
# each one produces. Generated from the guard's own builders, so a reworded
# branch fails the classification tests instead of silently reporting zero.
GUARD_BUILDERS = {
    "build_allow_reason": lambda: guard.build_allow_reason(),
    "build_reason": lambda: guard.build_reason("gh_run_watch"),
    "build_duplicate_reason": lambda: guard.build_duplicate_reason(
        "41", ["task-1"]),
    "overlap.build_reason": lambda: overlap.build_reason(
        [("41", ["src/synthetic.py"], True)]),
}

GUARD_CATEGORIES = {
    "build_allow_reason": "auto-allow",
    "build_reason": "poll",
    "build_duplicate_reason": "duplicate",
    "overlap.build_reason": "overlap",
}


def guard_reason_builders():
    """Every builder named at a `permissionDecisionReason` call site."""
    text = GUARD.read_text(encoding="utf-8")
    return set(re.findall(r"'permissionDecisionReason':\s*([\w.]+)\(", text))

def _signatures():
    """The real nudge and Stop-block texts, from the hooks' own builders.

    Both read CLAUDE_PLUGIN_ROOT at call time, so it is set only across these
    calls and restored afterwards — a module-scope assignment would leak into
    the sibling suites, which assert on their own plugin root.
    """
    saved = os.environ.get("CLAUDE_PLUGIN_ROOT")
    os.environ["CLAUDE_PLUGIN_ROOT"] = PLUGIN_ROOT
    try:
        return (hook.build_context("pr_create", "41"),
                hook.build_context("push", "41"),
                hook.build_context("push", None),
                stop_hook.build_reason(["41"]))
    finally:
        if saved is None:
            os.environ.pop("CLAUDE_PLUGIN_ROOT", None)
        else:
            os.environ["CLAUDE_PLUGIN_ROOT"] = saved


NUDGE_CREATE, NUDGE_PUSH, NUDGE_PUSH_UNRESOLVED, STOP_REASON = _signatures()

# Every remaining string a hook hands the model or the human, beside the guard's
# four reasons above: both PostToolUse nudges, the Stop block, and the Stop
# hook's non-blocking notice. Keyed by module, so the two `build_reason`s stay
# apart. Each entry yields every text its builder can produce.
HOOK_MESSAGES = {
    "hook.build_context": lambda: (NUDGE_CREATE, NUDGE_PUSH,
                                   NUDGE_PUSH_UNRESOLVED),
    "hook.build_live_context": lambda: (
        hook.build_live_context("41", ["task-1"]),),
    "stop_hook.build_reason": lambda: (STOP_REASON,),
    "stop_hook.build_warning": lambda: (
        stop_hook.build_warning({"41": "check_failure"}),),
}


def hook_message_builders():
    """Every builder feeding an agent-facing field in the two non-guard hooks.

    The Stop hook names its builder at the assignment. The PostToolUse hook
    picks one into `context` a few lines above its single emission site, so the
    branch is read off that assignment rather than off the `print`.
    """
    nudges = re.findall(r"\bcontext = (\w+)\(", HOOK.read_text(encoding="utf-8"))
    stop = re.findall(r"out\['(?:reason|systemMessage)'\] = (\w+)\(",
                      STOP_HOOK.read_text(encoding="utf-8"))
    return {"hook." + n for n in nudges} | {"stop_hook." + n for n in stop}


WATCHER_PATH = os.path.join(PLUGIN_ROOT, "scripts", "pr-sentinel-watch.sh")


def watcher_event_names():
    """Every event the watcher emits, from its own `report_header` call sites."""
    text = WATCHER.read_text(encoding="utf-8")
    return set(re.findall(r"^\s*report_header\s+([a-z_]+)\s*$", text, re.M))


def report_text(event, pr, extra="State: OPEN"):
    """A watcher report as it reaches the transcript."""
    return "PR-SENTINEL EVENT: %s\nPR: %s\n%s" % (event, pr, extra)


def numbered(text):
    """The same text as the Read tool renders it — `<lineno>\\t` prefixes."""
    return "\n".join("%6d\t%s" % (i, l)
                     for i, l in enumerate(text.split("\n"), 1))


# --- transcript record builders ---------------------------------------------

TS = "2026-08-18T12:00:00.000Z"
CWD = "/synthetic/workspace/demo-repo"


def rec_nudge(context, ts=TS, cwd=CWD, tool_use_id="toolu_nudge"):
    stdout = json.dumps({"hookSpecificOutput": {
        "hookEventName": "PostToolUse", "additionalContext": context}})
    return {"type": "attachment", "timestamp": ts, "cwd": cwd,
            "attachment": {"type": "hook_success",
                           "hookName": "PostToolUse:Bash",
                           "toolUseID": tool_use_id, "stdout": stdout}}


def rec_launch(pr, background=True, ts=TS, cwd=CWD, tool_use_id="toolu_launch",
               command=None):
    cmd = command if command is not None \
        else 'bash "%s" %s' % (WATCHER_PATH, pr)
    return {"type": "assistant", "timestamp": ts, "cwd": cwd,
            "message": {"role": "assistant", "content": [
                {"type": "tool_use", "id": tool_use_id, "name": "Bash",
                 "input": {"command": cmd, "run_in_background": background}}]}}


def rec_bash(command, ts=TS, cwd=CWD, tool_use_id="toolu_bash"):
    """A Bash tool_use that is not a watcher launch."""
    return rec_launch(None, ts=ts, cwd=cwd, tool_use_id=tool_use_id,
                      command=command)


def rec_result(text, ts=TS, cwd=CWD, tool_use_id="toolu_result"):
    return {"type": "user", "timestamp": ts, "cwd": cwd,
            "message": {"role": "user", "content": [
                {"type": "tool_result", "tool_use_id": tool_use_id,
                 "content": text}]}}


def rec_guard_allow(reason=None, ts=TS, cwd=CWD, tool_use_id="toolu_guard",
                    atype="hook_success", stdout=None):
    """A PreToolUse attachment carrying the guard's verdict."""
    if stdout is None:
        stdout = json.dumps({"hookSpecificOutput": {
            "hookEventName": "PreToolUse", "permissionDecision": "allow",
            "permissionDecisionReason":
                reason if reason is not None else guard.build_allow_reason()}})
    return {"type": "attachment", "timestamp": ts, "cwd": cwd,
            "attachment": {
                "type": atype, "hookName": "PreToolUse:Bash",
                "command": 'python3 "/plugins/pr-sentinel/scripts/'
                           'pr-sentinel-guard.py"',
                "toolUseID": tool_use_id, "stdout": stdout}}


def rec_guard_deny(reason, ts=TS, cwd=CWD, tool_use_id="toolu_bash"):
    """The error a denied call hands back — the only record of a deny."""
    rec = rec_result(reason, ts=ts, cwd=cwd, tool_use_id=tool_use_id)
    rec["message"]["content"][0]["is_error"] = True
    return rec


def rec_stop_block(reason, ts=TS, cwd=CWD):
    return {"type": "system", "subtype": "stop_hook_summary", "timestamp": ts,
            "cwd": cwd, "hookCount": 1, "hookErrors": [reason]}


class TranscriptCase(unittest.TestCase):
    """Writes synthetic transcripts and runs the collector over them."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.addCleanup(self.tmp.cleanup)
        self._n = 0

    def write(self, records, name=None):
        self._n += 1
        proj = self.root / ("project-%d" % self._n)
        proj.mkdir(parents=True, exist_ok=True)
        path = proj / (name or "session.jsonl")
        with open(path, "w", encoding="utf-8") as fh:
            for r in records:
                fh.write(json.dumps(r) + "\n")
        return path

    def report(self, since="all", repo=""):
        cutoff = None if since == "all" else fr.parse_since(since)
        paths = sorted(str(p) for p in self.root.glob("**/*.jsonl"))
        return fr.build_report(fr.collect(paths, cutoff, repo))


